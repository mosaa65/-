#include <iostream>
#include <string>
#include <iomanip> // لتنسيق الإخراج
using namespace std;

// ====== تعريف Struct الجهاز ======
struct Device {
    string name;         // اسم الجهاز
    string manufacturer; // الشركة المصنعة
    double price;        // السعر (يجب أن يكون > 0)
    int    quantity;     // الكمية المتاحة (يجب أن تكون > 0)

    // --- دالة إدخال بيانات الجهاز (داخل الـ struct) ---
    void inputData() {
        cout << "    اسم الجهاز      : ";
        cin.ignore();
        getline(cin, name);

        cout << "    الشركة المصنعة  : ";
        getline(cin, manufacturer);

        // التحقق من صحة السعر
        do {
            cout << "    السعر (ريال)    : ";
            cin >> price;
            if (price <= 0)
                cout << "    ⚠️  السعر يجب أن يكون أكبر من صفر!" << endl;
        } while (price <= 0);

        // التحقق من صحة الكمية
        do {
            cout << "    الكمية المتاحة  : ";
            cin >> quantity;
            if (quantity <= 0)
                cout << "    ⚠️  الكمية يجب أن تكون أكبر من صفر!" << endl;
        } while (quantity <= 0);
    }

    // --- دالة عرض بيانات الجهاز (داخل الـ struct) ---
    void displayData() const {
        cout << "  | " << setw(20) << left << name
             << " | " << setw(15) << left << manufacturer
             << " | " << setw(10) << right << price
             << " | " << setw(8)  << right << quantity
             << "  |" << endl;
    }

    // --- دالة عرض التقرير المفصل ---
    void displayReport() const {
        cout << "  ┌─────────────────────────────────┐" << endl;
        cout << "  │ الجهاز       : " << name           << endl;
        cout << "  │ الشركة       : " << manufacturer   << endl;
        cout << "  │ السعر        : " << price << " ريال" << endl;
        cout << "  │ الكمية       : " << quantity << " قطعة" << endl;
        cout << "  │ القيمة الكلية: " << price * quantity << " ريال" << endl;
        cout << "  └─────────────────────────────────┘" << endl;
    }
};

// ====== الدالة الرئيسية ======
int main() {

    cout << "============================================" << endl;
    cout << "   نظام إدارة الأجهزة الإلكترونية" << endl;
    cout << "============================================" << endl;

    int n;
    cout << "أدخل عدد الأجهزة: ";
    cin >> n;

    Device devices[100];

    // ------- إدخال بيانات الأجهزة -------
    for (int i = 0; i < n; i++) {
        cout << "\n--- الجهاز رقم " << i + 1 << " ---" << endl;
        devices[i].inputData();
    }

    // ------- عرض جميع الأجهزة في جدول -------
    cout << "\n============================================" << endl;
    cout << "             قائمة الأجهزة" << endl;
    cout << "============================================" << endl;
    cout << "  | " << setw(20) << left << "اسم الجهاز"
         << " | " << setw(15) << left << "الشركة"
         << " | " << setw(10) << right << "السعر"
         << " | " << setw(8)  << right << "الكمية"
         << "  |" << endl;
    cout << "  |-----------------------------------------|" << endl;

    for (int i = 0; i < n; i++) {
        devices[i].displayData();
    }

    // ------- عرض التقرير المفصل -------
    cout << "\n============================================" << endl;
    cout << "           التقرير المفصل للأجهزة" << endl;
    cout << "============================================" << endl;

    for (int i = 0; i < n; i++) {
        cout << "\n جهاز رقم " << i + 1 << ":" << endl;
        devices[i].displayReport();
    }

    cout << "\n============================================" << endl;
    return 0;
}

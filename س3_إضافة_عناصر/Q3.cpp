#include <iostream>
using namespace std;

int main() {

    cout << "======================================" << endl;
    cout << "   برنامج إضافة عناصر للمصفوفة" << endl;
    cout << "======================================" << endl;

    // ------- الخطوة 1: إدخال المصفوفة -------
    int n;
    cout << "أدخل عدد العناصر الأولية: ";
    cin >> n;

    // نحجز مساحة إضافية لاستيعاب العنصرين الجديدين
    int arr[102];
    cout << "\nأدخل " << n << " رقم:" << endl;
    for (int i = 0; i < n; i++) {
        cout << "  العنصر [" << i + 1 << "]: ";
        cin >> arr[i];
    }

    // ------- الخطوة 2: عرض المصفوفة الأصلية -------
    cout << "\n--- المصفوفة قبل الإضافة ---" << endl;
    cout << "عدد العناصر: " << n << endl;
    cout << "[ ";
    for (int i = 0; i < n; i++) {
        cout << arr[i];
        if (i < n - 1) cout << ", ";
    }
    cout << " ]" << endl;

    // ------- الخطوة 3: إضافة عنصرين جديدين -------
    int elem1, elem2;
    cout << "\n--- إضافة عنصرين جديدين ---" << endl;
    cout << "أدخل العنصر الأول الجديد: ";
    cin >> elem1;
    cout << "أدخل العنصر الثاني الجديد: ";
    cin >> elem2;

    // إضافة العنصرين في نهاية المصفوفة
    arr[n]     = elem1;
    arr[n + 1] = elem2;
    n = n + 2; // تحديث الحجم الكلي

    // ------- الخطوة 4: عرض المصفوفة بعد الإضافة -------
    cout << "\n--- المصفوفة بعد الإضافة ---" << endl;
    cout << "عدد العناصر: " << n << endl;
    cout << "[ ";
    for (int i = 0; i < n; i++) {
        cout << arr[i];
        if (i < n - 1) cout << ", ";
    }
    cout << " ]" << endl;

    cout << "\n✅ تمت إضافة العنصرين بنجاح!" << endl;
    cout << "======================================" << endl;
    return 0;
}
